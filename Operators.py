# Operator is a symbol that performs an operation on one or more operands (values or variables).

# 1. Arithmetic Operators: mathematical operations like addition, subtraction, multiplication,division, etc.
# - Subtract
# * Multiply
# / Divide
# % Modulus
# ** Power
# // Floor Division

# 2. relational Operators: used to compare two values and return a boolean result (True or False).
# < - less than
# > - greater than
# <= - less than or equal to
# >= - greater than or equal to 
# == -  equal to
# != - not equal to

# 3. Assignment Operators:  used to assign values to variables. 
#  =    - Assign
# +=    - Add and assign
# -=    - Subtract and assign
# *=    - Multiply and assign
# /=    - Divide and assign
# %=    - Modulus and assign
# **=   - Power and assign
# //=   - Floor Division and assign

# 4. Logical Operators:  used to combine conditional statements. 
# and - Returns True if both statements are true
# or - Returns True if one of the statements is true
# not - Reverse the result, returns False if the result is true

# 5. membership Operators:  used to test whether a value is present in a sequence (like a list, tuple, or string). 
# in    -  Returns True if a sequence with the specified value is present in the object
# not in - Returns True if a sequence with the specified value is not present in the object

# 6. Identity Operators:  used to compare the variables or any objects are having same identity or not. 
# is     -  Returns True if both variables are the same identity
# is not -  Returns True if both variables are not the same identity
# id() -  built in function, used to find the memory address of the object, it returns a unique integer for the object during its lifetime.

# 7. bitwise Operators:  used to perform bit-level operations on binary numbers. 
# & -  AND 
# | -  OR
# ^ -  XOR
# ~ -  NOT
# << -  Left Shift
# >> -  Right Shift